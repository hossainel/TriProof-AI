<?php

namespace App\Services;

use App\Models\PurchaseOrder;
use App\Models\ScanLog;
use App\Models\SerialRegistry;
use App\Models\User;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use Symfony\Component\Process\Process;

class SerialGapAnalyticsService
{
    /**
     * German Tank Problem estimator: N_hat = m + (m / k) - 1.
     * Pure and deterministic so it remains testable without DuckDB.
     *
     * @param  array<int, mixed>  $serials
     * @return array<string, float|int|null>
     */
    public function estimate(array $serials): array
    {
        $values = [];
        foreach ($serials as $value) {
            if (is_numeric($value) && (int) $value > 0) {
                $values[] = (int) $value;
            }
        }

        if ($values === []) {
            return ['observed' => 0, 'max' => null, 'estimate' => null, 'coverage' => null];
        }

        $k = count($values);
        $m = max($values);
        $estimate = $m + ($m / $k) - 1;

        return [
            'observed' => $k,
            'max' => $m,
            'estimate' => round($estimate, 2),
            'coverage' => $estimate > 0 ? round($m / $estimate, 4) : null,
        ];
    }

    /**
     * Export an immutable daily snapshot and, when the DuckDB CLI is present,
     * materialize storage/analytics/triproof.duckdb.
     *
     * @return array<string, mixed>
     */
    public function exportSnapshot(?Carbon $date = null): array
    {
        $date = $date ?? now();
        $day = $date->toDateString();
        $snapshotDir = (string) config('triproof.analytics.snapshot_dir', storage_path('analytics/snapshots'));
        $databasePath = (string) config('triproof.analytics.duckdb_path', storage_path('analytics/triproof.duckdb'));

        File::ensureDirectoryExists($snapshotDir);
        File::ensureDirectoryExists(dirname($databasePath));

        $serials = SerialRegistry::query()
            ->whereDate('created_at', $day)
            ->limit(100000)
            ->get(['id', 'po_id', 'factory_id', 'batch_id', 'unit_number', 'outer_serial', 'status']);

        $scans = ScanLog::query()
            ->whereDate('scanned_at', $day)
            ->limit(100000)
            ->get(['id', 'outer_serial', 'cloud_cross_check_verdict', 'scanned_at']);

        $serialJson = $serials->map(fn ($row) => json_encode([
            'id' => $row->id,
            'po_id' => $row->po_id,
            'factory_id' => $row->factory_id,
            'batch_id' => $row->batch_id,
            'unit_number' => $row->unit_number,
            'outer_serial' => $row->outer_serial,
            'status' => $row->status?->value,
        ], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES))->implode("\n");

        $scanJson = $scans->map(fn ($row) => json_encode([
            'id' => $row->id,
            'outer_serial' => $row->outer_serial,
            'verdict' => $row->cloud_cross_check_verdict?->value,
            'scanned_at' => $row->scanned_at?->toIso8601String(),
        ], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES))->implode("\n");

        $serialSnapshot = $snapshotDir.'/serial_registry-'.$day.'.jsonl';
        $scanSnapshot = $snapshotDir.'/scan_logs-'.$day.'.jsonl';
        File::put($serialSnapshot, $serialJson === '' ? '' : $serialJson."\n");
        File::put($scanSnapshot, $scanJson === '' ? '' : $scanJson."\n");

        $sqlPath = dirname($databasePath).'/triproof.duckdb.sql';
        File::put($sqlPath, implode("\n", [
            "-- Generated by SerialGapAnalyticsService for {$day}",
            "COPY (SELECT * FROM read_json_auto('{$serialSnapshot}')) TO '{$snapshotDir}/serial_registry-{$day}.parquet' (FORMAT PARQUET);",
            "COPY (SELECT * FROM read_json_auto('{$scanSnapshot}')) TO '{$snapshotDir}/scan_logs-{$day}.parquet' (FORMAT PARQUET);",
            'CREATE TABLE IF NOT EXISTS serial_registry AS SELECT * FROM read_json_auto(\''.$serialSnapshot.'\');',
            'CREATE TABLE IF NOT EXISTS scan_logs AS SELECT * FROM read_json_auto(\''.$scanSnapshot.'\');',
            '',
        ]));

        $duckdb = $this->duckdbBinary();
        if ($duckdb === null) {
            return [
                'date' => $day,
                'driver' => 'php_json_snapshot',
                'duckdb_available' => false,
                'serial_rows' => $serials->count(),
                'scan_rows' => $scans->count(),
                'sql_script' => $sqlPath,
                'snapshots' => [$serialSnapshot, $scanSnapshot],
            ];
        }

        try {
            $process = new Process([$duckdb, $databasePath, '-c', "READ '{$sqlPath}'"], null, null, null, 30);
            $process->mustRun();

            return [
                'date' => $day,
                'driver' => 'duckdb',
                'duckdb_available' => true,
                'database' => $databasePath,
                'serial_rows' => $serials->count(),
                'scan_rows' => $scans->count(),
                'sql_script' => $sqlPath,
                'snapshots' => [$serialSnapshot, $scanSnapshot],
            ];
        } catch (\Throwable $exception) {
            report($exception);

            return [
                'date' => $day,
                'driver' => 'php_json_snapshot',
                'duckdb_available' => true,
                'error' => 'DuckDB execution failed; JSON snapshots remain available.',
                'sql_script' => $sqlPath,
                'snapshots' => [$serialSnapshot, $scanSnapshot],
            ];
        }
    }

    /**
     * @return array<string, mixed>
     */
    public function dashboardPayload(User $user, ?int $poId = null): array
    {
        $orderQuery = PurchaseOrder::query()->visibleTo($user);
        if ($poId !== null) {
            $orderQuery->whereKey($poId);
        }
        $poIds = (clone $orderQuery)->select('purchase_orders.id');

        $serials = SerialRegistry::query()
            ->whereIn('po_id', $poIds)
            ->limit(50000)
            ->pluck('unit_number')
            ->all();

        $velocity = ScanLog::query()
            ->join('serial_registry', 'serial_registry.outer_serial', '=', 'scan_logs.outer_serial')
            ->whereIn('serial_registry.po_id', $poIds)
            ->select(DB::raw('DATE(scan_logs.scanned_at) as day'), DB::raw('COUNT(*) as total'))
            ->groupBy('day')
            ->orderBy('day')
            ->limit(60)
            ->get()
            ->map(fn ($row) => ['day' => (string) $row->day, 'scans' => (int) $row->total])
            ->all();

        $distribution = [];
        $values = array_values(array_filter($serials, fn ($value) => is_numeric($value) && (int) $value > 0));
        if ($values !== []) {
            $min = min($values);
            $max = max($values);
            $buckets = 12;
            $width = max(1, (int) ceil(($max - $min + 1) / $buckets));
            for ($start = $min; $start <= $max; $start += $width) {
                $end = $start + $width - 1;
                $distribution[] = [
                    'label' => $start.'–'.$end,
                    'count' => count(array_filter($values, fn ($value) => $value >= $start && $value <= $end)),
                ];
            }
        }

        return [
            'estimate' => $this->estimate($values),
            'distribution' => $distribution,
            'scan_velocity' => $velocity,
            'generated_at' => now()->toIso8601String(),
        ];
    }

    private function duckdbBinary(): ?string
    {
        $candidates = ['duckdb', '/usr/local/bin/duckdb', '/usr/bin/duckdb'];

        foreach ($candidates as $candidate) {
            $process = new Process(['test', '-x', $candidate]);
            $process->run();
            if ($process->isSuccessful()) {
                return $candidate;
            }
        }

        return null;
    }
}
